#!/usr/bin/env python3
"""Generate the checked-in macOS x64 runtime from the shared assembly."""
from pathlib import Path
import re
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
shared = (root / 'tools/native-runtime/runtime.S').read_text()
shim = (root / 'tools/macos-runtime/runtime.S').read_text()

def replace_once(old, new):
    global shared
    if shared.count(old) != 1:
        raise RuntimeError(f'shared runtime changed: expected one {old!r}')
    shared = shared.replace(old, new)

# LC_MAIN supplies argc, argv, and envp in registers. Preserve them in
# otherwise-unused heap-state bytes before initialization overwrites them.
replace_once('rt_init:\n', 'rt_init:\n push rdi\n push rsi\n push rdx\n')
replace_once(' mov r15,rax\n mov qword ptr [r15+16],1048576',
             ' mov r15,rax\n mov rax,[rsp+16]\n mov [r15+4304],rax\n'
             ' mov rax,[rsp+8]\n mov [r15+4312],rax\n'
             ' mov rax,[rsp]\n mov [r15+4320],rax\n'
             ' mov qword ptr [r15+16],1048576')
replace_once(' jb .init_char\n ret\nrt_alloc:',
             ' jb .init_char\n add rsp,24\n ret\nrt_alloc:')

# The platform layer supplies a register-based rt_args implementation.
args_start = shared.index('rt_args:\n')
args_end = shared.index('# Run a trusted, prequoted host command', args_start)
shared = shared[:args_start] + shared[args_end:]
replace_once(' mov rdx,[r14]\n lea rdx,[r14+rdx*8+16]\n mov eax,59',
             ' mov rdx,[r15+4320]\n mov eax,59')
shared = re.sub(r'(?m)^(\s*)syscall\s*$', r'\1call mac_syscall', shared)

# Both assembly sources contain local dot labels; give shim labels a prefix.
for label in set(re.findall(r'(?m)^(\.[A-Za-z_]\w*):', shim)):
    shim = re.sub(r'(?<!\w)' + re.escape(label) + r'\b',
                  '.mac_' + label[1:], shim)
with tempfile.TemporaryDirectory() as temp:
    assembly = Path(temp) / 'macos-runtime.S'
    obj = Path(temp) / 'macos-runtime.o'
    binary = Path(temp) / 'macos-runtime.bin'
    assembly.write_text(shared + '\n' + shim)
    subprocess.run(['as', '--64', str(assembly), '-o', str(obj)], check=True)
    relocations = subprocess.check_output(['objdump', '-r', str(obj)], text=True)
    if 'R_X86_64' in relocations:
        raise RuntimeError('macOS runtime has unresolved relocations: ' + relocations)
    subprocess.run(['objcopy', '-O', 'binary', '-j', '.text', str(obj), str(binary)], check=True)
    data = binary.read_bytes().hex()
    symbols = subprocess.check_output(['nm', '--defined-only', str(obj)], text=True)
    offsets = {name: int(address, 16) for address, kind, name in
               (line.split() for line in symbols.splitlines())}

imports = {
    'mac_mmap': '_mmap', 'mac_munmap': '_munmap',
    'mac_read': '_read', 'mac_write': '_write',
    'mac_open': '_open', 'mac_close': '_close',
    'mac_lseek': '_lseek', 'mac_ioctl': '_ioctl',
    'mac_mkdir': '_mkdir', 'mac_fork': '_fork',
    'mac_execve': '_execve', 'mac_waitpid': '_waitpid',
    'mac_exit': '_exit', 'mac_errno': '___error',
}
for symbol in imports:
    if symbol not in offsets:
        raise RuntimeError(f'missing import stub {symbol}')

lines = ['// Generated by tools/macos-runtime/generate.py. Do not edit.',
         'namespace Hydrogen.Compiler.CodeGen.X64 {',
         '    public class MacOSRuntimeEmitter {',
         '        private int runtimeStart;',
         '        public void Emit(X64Assembler code) {',
         '            runtimeStart = code.Position();',
         '            string bytes = "";']
for start in range(0, len(data), 160):
    lines.append(f'            bytes = bytes + "{data[start:start+160]}";')
lines += ['            int i = 0;',
          '            while (i < bytes.Length) {',
          '                code.EmitByte(Digit(bytes[i]) * 16 + Digit(bytes[i + 1]));',
          '                i = i + 2;',
          '            }', '        }',
          '        public int Offset(string name) {']
for name in sorted(offsets):
    if name.startswith('rt_'):
        lines.append(f'            if (name == "{name}") {{ return {offsets[name]}; }}')
lines += ['            return -1;', '        }',
          '        public int[] ExternalCallOffsets() {',
          f'            int[] result = new int[{len(imports)}];']
for index, symbol in enumerate(imports):
    lines.append(f'            result[{index}] = runtimeStart + {offsets[symbol] + 2};')
lines += ['            return result;', '        }',
          '        public string[] ExternalSymbols() {',
          f'            string[] result = new string[{len(imports)}];']
for index, symbol in enumerate(imports.values()):
    lines.append(f'            result[{index}] = "{symbol}";')
lines += ['            return result;', '        }',
          '        private int Digit(string ch) {']
for value, ch in enumerate('0123456789abcdef'):
    lines.append(f'            if (ch == "{ch}") {{ return {value}; }}')
lines += ['            return 0;', '        }', '    }', '}']
target = root / 'src/Hydrogen.Compiler.CodeGen.X64/MacOSRuntimeEmitter.hy'
target.write_text('\n'.join(lines) + '\n')
print(f'{len(data)//2} macOS runtime bytes -> {target.relative_to(root)}')
