#!/usr/bin/env python3
"""Build the Windows Win32-backed runtime blob with development binutils.

The self-hosted compiler embeds the generated bytes and emits PE files without
requiring an assembler, linker, C toolchain, or Windows SDK at use time.
"""
from pathlib import Path
import re
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
linux = (root / 'tools/native-runtime/runtime.S').read_text()
shim = (root / 'tools/windows-runtime/shim.S').read_text()
linux = linux.replace('rt_is_windows:\n    xor eax, eax\n    ret',
                      'rt_is_windows:\n    mov eax, 1\n    ret')
# VirtualFree releases a whole VirtualAlloc reservation. Keep one page per
# reservation on Windows while Linux parcels pages from a larger mmap batch.
span_start = linux.index('rt_span_page:\n')
span_end = linux.index('rt_page_hash:\n', span_start)
linux = linux[:span_start] + '''rt_span_page:
 mov eax,9
 xor edi,edi
 mov esi,4096
 mov edx,3
 mov r10d,0x22
 mov r8,-1
 xor r9d,r9d
 syscall
 cmp rax,-4095
 jae rt_oom
 ret
''' + linux[span_end:]
# Windows reservations remain independent even when their addresses are
# adjacent. Release each dead span with its original VirtualAlloc base.
sweep_start = linux.index('.sweep_span:\n')
sweep_end = linux.index('.keep_span:\n', sweep_start)
linux = linux[:sweep_start] + '''.sweep_span:
 mov rbx,[r13]
 test rbx,rbx
 jz .sweep_next_class
 cmp qword ptr [rbx+40],0
 jne .keep_span
 mov rax,[rbx]
 mov [r13],rax
 mov rdi,rbx
 mov esi,4096
 mov eax,11
 syscall
 jmp .sweep_span
''' + linux[sweep_end:]
# GNU as dot labels are file scoped, so prefix shim labels before appending.
for label in set(re.findall(r'(?m)^(\.[A-Za-z_]\w*):', shim)):
    shim = re.sub(r'(?<!\w)' + re.escape(label) + r'\b', '.win_' + label[1:], shim)
linux = linux[:linux.index('rt_args:\n')] + linux[linux.index('rt_null_error:\n'):]
linux = re.sub(r'(?m)^(\s*)syscall\s*$', r'\1call win_syscall', linux)
# Native Windows paths also use backslashes. Skip the separator immediately
# after a drive letter: it denotes the volume root, not a directory to create.
if ' cmp byte ptr [rbx+r13],47\n jne .mkdir_next\n test r13,r13\n jz .mkdir_next\n' not in linux:
    raise RuntimeError('The shared runtime parent-directory loop changed')
linux = linux.replace(
    ' cmp byte ptr [rbx+r13],47\n jne .mkdir_next\n test r13,r13\n jz .mkdir_next\n',
    ' cmp byte ptr [rbx+r13],47\n je .win_mkdir_separator\n'
    ' cmp byte ptr [rbx+r13],92\n jne .mkdir_next\n'
    '.win_mkdir_separator:\n test r13,r13\n jz .mkdir_next\n'
    ' cmp r13,2\n jne .win_mkdir_cut\n'
    ' cmp byte ptr [rbx+1],58\n je .mkdir_next\n'
    '.win_mkdir_cut:\n')
source = linux + '\n' + shim
with tempfile.TemporaryDirectory() as temp:
    assembly = Path(temp) / 'windows-runtime.S'
    obj = Path(temp) / 'windows-runtime.o'
    binary = Path(temp) / 'windows-runtime.bin'
    assembly.write_text(source)
    subprocess.run(['as', '--64', str(assembly), '-o', str(obj)], check=True)
    relocations = subprocess.check_output(['objdump', '-r', str(obj)], text=True)
    if 'R_X86_64' in relocations:
        raise RuntimeError('Windows runtime must contain no unresolved relocations: ' + relocations)
    subprocess.run(['objcopy', '-O', 'binary', '-j', '.text', str(obj), str(binary)], check=True)
    data = binary.read_bytes().hex()
    symbols = subprocess.check_output(['nm', '--defined-only', str(obj)], text=True)
    offsets = {name: int(address, 16) for address, kind, name in
               (line.split() for line in symbols.splitlines())
               if name.startswith('rt_') or name.startswith('win_')}

lines = ['// Generated by tools/windows-runtime/generate.py. Do not edit.',
         'namespace Hydrogen.Compiler.CodeGen.X64 {', '    public class WindowsRuntimeEmitter {',
         '        public void Emit(X64Assembler code) {', '            string bytes = "";']
for start in range(0, len(data), 160):
    lines.append(f'            bytes = bytes + "{data[start:start+160]}";')
lines += ['            int i = 0;', '            while (i < bytes.Length) {',
          '                code.EmitByte(Digit(bytes[i]) * 16 + Digit(bytes[i + 1]));',
          '                i = i + 2;', '            }', '        }',
          '        public int Offset(string name) {']
for name, offset in sorted(offsets.items()):
    lines.append(f'            if (name == "{name}") {{ return {offset}; }}')
lines += ['            return -1;', '        }', '        private int Digit(string ch) {']
for value, ch in enumerate('0123456789abcdef'):
    lines.append(f'            if (ch == "{ch}") {{ return {value}; }}')
lines += ['            return 0;', '        }', '    }', '}']
target = root / 'src/Hydrogen.Compiler.CodeGen.X64/WindowsRuntimeEmitter.hy'
target.write_text('\n'.join(lines) + '\n')
print(f'{len(data)//2} Windows runtime bytes -> {target.relative_to(root)}')
